// One-off: downloads the latin subset of the certificate fonts from Google Fonts
// and writes them (base64) to lib/certificate-fonts.ts.
import fs from 'node:fs';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const faces = [
  { family: 'Cinzel', query: 'Cinzel:wght@600..800', css: { weight: '600 800', style: 'normal' } },
  { family: 'Playfair Display', query: 'Playfair+Display:ital,wght@0,600..800', css: { weight: '600 800', style: 'normal' } },
  { family: 'Playfair Display', query: 'Playfair+Display:ital,wght@1,600..800', css: { weight: '600 800', style: 'italic' } },
  { family: 'Montserrat', query: 'Montserrat:wght@500..800', css: { weight: '500 800', style: 'normal' } },
  { family: 'Great Vibes', query: 'Great+Vibes', css: { weight: '400', style: 'normal' } },
];

let out = '// Generated by scripts/build-cert-fonts.mjs - do not edit by hand.\nexport const CERTIFICATE_FONT_CSS = `\n';

for (const face of faces) {
  const cssText = await (
    await fetch(`https://fonts.googleapis.com/css2?family=${face.query}&display=swap`, { headers: { 'User-Agent': UA } })
  ).text();
  const latin = cssText.split('/* latin */')[1];
  const url = latin?.match(/url\((https:[^)]+)\)/)?.[1];
  if (!url) throw new Error(`no latin subset for ${face.family}`);
  const data = Buffer.from(await (await fetch(url)).arrayBuffer());
  console.log(face.family, face.css.style, Math.round(data.length / 1024) + 'KB');
  out += `@font-face{font-family:'${face.family}';font-style:${face.css.style};font-weight:${face.css.weight};src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2');}\n`;
}

out += '`;\n';
fs.writeFileSync('lib/certificate-fonts.ts', out);
